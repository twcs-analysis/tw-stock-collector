#!/bin/bash

# 重新抓取 2025 年的股價資料
# 從 2025-01-02 開始逐日抓取

echo "開始重新抓取 2025 年股價資料..."

# 2025 年 1 月
for day in 02 03 06 07 08 09 10 13 14 15 16 17 20 21 22 23 24 27 28 29 30; do
    date="2025-01-$day"
    echo "=========================================="
    echo "抓取日期: $date"
    echo "=========================================="
    python scripts/run_collection.py --date $date --types price --skip-trading-day-check
    if [ $? -ne 0 ]; then
        echo "❌ $date 抓取失敗"
    else
        echo "✅ $date 抓取完成"
    fi
    sleep 2
done

# 2025 年 2 月（截至今天 2026-02-01，可能只有部分交易日）
# 先不抓取，因為今天是 2026-02-01，2025 年 2 月到 12 月的資料需要確認

echo "=========================================="
echo "2025 年 1 月資料抓取完成"
echo "=========================================="
